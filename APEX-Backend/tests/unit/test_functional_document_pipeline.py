def test_docx_functional_scenarios_extraction():
    """Verify that BrdAnalyzer dynamically extracts all 41 scenarios from the uploaded DOCX."""
    docx_path = Path("storage/migration-jobs/job_98b9b69f53d6/brd/EMS_Functional_Testing_Document.docx")
    if not docx_path.exists():
        pytest.skip(f"Test artifact {docx_path} not found")

    analyzer = BrdAnalyzer(docx_path, job_id="job_98b9b69f53d6")
    result = analyzer.extract()

    assert not result.error, f"Extraction failed with error: {result.error}"
    assert len(result.workflows) == 41, f"Expected 41 workflows, got {len(result.workflows)}"

    # Check key scenarios
    first_wf = result.workflows[0]
    assert "FT-EMP-001" in first_wf.requirements_covered
    assert first_wf.target_method_hint == "POST"
    assert first_wf.target_endpoint_hint == "/api/employees"
    assert first_wf.expected_status_hint == 201
    assert not first_wf.is_negative

    # Check negative scenario
    neg_wf = next((w for w in result.workflows if "FT-ERR-001" in w.requirements_covered), None)
    assert neg_wf is not None
    assert neg_wf.is_negative
    assert neg_wf.expected_status_hint == 404


def test_proposed_test_generator_preserves_functional_doc():
    """Verify ProposedTestGenerator generates separate, distinct proposals for LLM and Functional Doc."""
    docx_path = Path("storage/migration-jobs/job_98b9b69f53d6/brd/EMS_Functional_Testing_Document.docx")
    if not docx_path.exists():
        pytest.skip(f"Test artifact {docx_path} not found")

    analyzer = BrdAnalyzer(docx_path, job_id="job_test")
    brd_result = analyzer.extract()

    mock_analysis = {
        "endpoints": [
            {"method": "GET", "endpoint": "/api/employees", "class_name": "EmployeeController"},
            {"method": "POST", "endpoint": "/api/employees", "class_name": "EmployeeController"},
        ],
        "ui_workflows": [
            {"name": "EmployeeList", "route": "/employees", "has_table": True},
        ],
    }

    generator = ProposedTestGenerator(mock_analysis, brd_analysis=brd_result)
    proposals = generator.generate()

    doc_proposals = [p for p in proposals if p.generation_source == "FUNCTIONAL_DOC" or p.source == "Functional Doc"]
    ai_proposals = [p for p in proposals if p.generation_source != "FUNCTIONAL_DOC" and p.source != "Functional Doc"]

    assert len(doc_proposals) == 41, f"Expected 41 Functional Doc proposals, got {len(doc_proposals)}"
    assert len(ai_proposals) > 0, "Expected non-zero LLM Generated proposals"
    assert len(proposals) == len(doc_proposals) + len(ai_proposals)

    # Verify every Functional Doc proposal retains source metadata
    for p in doc_proposals:
        assert p.source == "Functional Doc"
        assert p.generation_source == "FUNCTIONAL_DOC"
        assert p.document_id == "EMS_Functional_Testing_Document.docx"


def test_proposed_test_service_metrics_breakdown():
    """Verify ProposedTestService accurately counts LLM Generated vs Functional Doc."""
    service = ProposedTestService()

    proposals = [
        ProposedTestCase(
            id="PTC-001",
            title="LLM Test",
            description="Generated by code analysis",
            type=ProposedTestType.API,
            priority=ProposedTestPriority.HIGH,
            source="LLM Generated",
            reason="Code analysis",
            expected_result="200 OK",
            status=ProposedTestStatus.PROPOSED,
            generation_source="LLM Generated",
        ),
        ProposedTestCase(
            id="PTC-002",
            title="Doc Test 1",
            description="Derived from doc",
            type=ProposedTestType.API,
            priority=ProposedTestPriority.HIGH,
            source="Functional Doc",
            reason="Document scenario",
            expected_result="201 Created",
            status=ProposedTestStatus.PROPOSED,
            generation_source="FUNCTIONAL_DOC",
        ),
        ProposedTestCase(
            id="PTC-003",
            title="Doc Test 2",
            description="Derived from doc",
            type=ProposedTestType.API,
            priority=ProposedTestPriority.MEDIUM,
            source="Functional Doc",
            reason="Document scenario",
            expected_result="200 OK",
            status=ProposedTestStatus.PROPOSED,
            generation_source="FUNCTIONAL_DOC",
        ),
    ]

    metrics = service._compute_metrics(proposals)
    assert metrics.total == 3
    assert metrics.llm_generated_count == 1
    assert metrics.functional_doc_generated_count == 2
    assert metrics.existing_count == 0
