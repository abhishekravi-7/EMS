"""JaCoCo Coverage Service for Java APEX.

Discovers, parses, and calculates JaCoCo line, branch, instruction, method, and class coverage metrics
from actual XML reports generated by Maven (target/site/jacoco/jacoco.xml) or
Gradle (build/reports/jacoco/test/jacocoTestReport.xml).
Also provides automated JaCoCo configuration injection for Maven and Gradle projects.
"""

from __future__ import annotations

import logging
import os
import re
import threading
import xml.etree.ElementTree as ET
from pathlib import Path
from typing import Any, Dict, List, Optional

from app.shared.command_runner import resolve_executable, run_command

logger = logging.getLogger(__name__)

STANDARD_JACOCO_XML_PATHS = [
    Path("target") / "site" / "jacoco" / "jacoco.xml",
    Path("target") / "site" / "jacoco-ut" / "jacoco.xml",
    Path("target") / "jacoco.xml",
    Path("build") / "reports" / "jacoco" / "test" / "jacocoTestReport.xml",
    Path("build") / "reports" / "jacoco" / "jacoco.xml",
]


class JaCoCoService:
    """Service to configure, discover, and parse real JaCoCo coverage metrics."""

    _dir_locks_guard = threading.Lock()
    _dir_locks: Dict[str, threading.Lock] = {}

    @classmethod
    def _get_dir_lock(cls, project_dir: Path) -> threading.Lock:
        try:
            key = str(project_dir.resolve())
        except Exception:
            key = str(project_dir)
        with cls._dir_locks_guard:
            if key not in cls._dir_locks:
                cls._dir_locks[key] = threading.Lock()
            return cls._dir_locks[key]

    @classmethod
    def ensure_jacoco_configured(cls, project_dir: Path) -> bool:
        """Inspects project build file (pom.xml or build.gradle) and ensures JaCoCo is configured.
        
        For Maven:
        - Injects org.jacoco:jacoco-maven-plugin:0.8.13 with prepare-agent and report executions
        - Preserves argLine property for Surefire instrumentation
        
        For Gradle:
        - Ensures jacoco plugin and jacocoTestReport task are present
        """
        if not project_dir.exists() or not project_dir.is_dir():
            return False

        pom_path = project_dir / "pom.xml"
        gradle_path = project_dir / "build.gradle"
        gradle_kts_path = project_dir / "build.gradle.kts"

        if pom_path.exists() and pom_path.is_file():
            return cls._ensure_maven_jacoco(pom_path)
        elif gradle_path.exists() and gradle_path.is_file():
            return cls._ensure_gradle_jacoco(gradle_path)
        elif gradle_kts_path.exists() and gradle_kts_path.is_file():
            return cls._ensure_gradle_kts_jacoco(gradle_kts_path)

        return False

    @staticmethod
    def _ensure_maven_jacoco(pom_path: Path) -> bool:
        """Ensures jacoco-maven-plugin is properly configured in pom.xml."""
        try:
            content = pom_path.read_text(encoding="utf-8", errors="replace")
            if "jacoco-maven-plugin" in content:
                logger.debug("jacoco-maven-plugin already configured in %s", pom_path)
                return True

            plugin_snippet = """
            <plugin>
                <groupId>org.jacoco</groupId>
                <artifactId>jacoco-maven-plugin</artifactId>
                <version>0.8.13</version>
                <executions>
                    <execution>
                        <id>prepare-agent</id>
                        <goals>
                            <goal>prepare-agent</goal>
                        </goals>
                    </execution>
                    <execution>
                        <id>report</id>
                        <phase>test</phase>
                        <goals>
                            <goal>report</goal>
                        </goals>
                    </execution>
                </executions>
            </plugin>"""

            if "</plugins>" in content:
                new_content = content.replace("</plugins>", f"{plugin_snippet}\n        </plugins>", 1)
            elif "<build>" in content and "</build>" in content:
                plugins_block = f"""
        <plugins>{plugin_snippet}
        </plugins>"""
                new_content = content.replace("</build>", f"{plugins_block}\n    </build>", 1)
            elif "</project>" in content:
                build_block = f"""
    <build>
        <plugins>{plugin_snippet}
        </plugins>
    </build>"""
                new_content = content.replace("</project>", f"{build_block}\n</project>", 1)
            else:
                return False

            pom_path.write_text(new_content, encoding="utf-8")
            logger.info("[JACOCO] Agent configured in %s", pom_path)
            return True
        except Exception as e:
            logger.warning("Failed to auto-configure JaCoCo in %s: %s", pom_path, e)
            return False

    @staticmethod
    def _ensure_gradle_jacoco(gradle_path: Path) -> bool:
        """Ensures jacoco plugin is configured in build.gradle."""
        try:
            content = gradle_path.read_text(encoding="utf-8", errors="replace")
            if "apply plugin: 'jacoco'" in content or 'apply plugin: "jacoco"' in content or "id 'jacoco'" in content or 'id "jacoco"' in content:
                logger.debug("JaCoCo already configured in %s", gradle_path)
                return True

            addition = """
apply plugin: 'jacoco'

jacocoTestReport {
    reports {
        xml.required = true
        html.required = true
    }
}
test.finalizedBy jacocoTestReport
"""
            gradle_path.write_text(content + "\n" + addition, encoding="utf-8")
            logger.info("[JACOCO] Agent configured in %s", gradle_path)
            return True
        except Exception as e:
            logger.warning("Failed to auto-configure JaCoCo in %s: %s", gradle_path, e)
            return False

    @staticmethod
    def _ensure_gradle_kts_jacoco(gradle_kts_path: Path) -> bool:
        """Ensures jacoco plugin is configured in build.gradle.kts."""
        try:
            content = gradle_kts_path.read_text(encoding="utf-8", errors="replace")
            if "jacoco" in content:
                return True

            addition = """
tasks.test {
    finalizedBy(tasks.jacocoTestReport)
}
tasks.jacocoTestReport {
    reports {
        xml.required.set(true)
        html.required.set(true)
    }
}
"""
            gradle_kts_path.write_text(content + "\n" + addition, encoding="utf-8")
            logger.info("[JACOCO] Agent configured in %s", gradle_kts_path)
            return True
        except Exception as e:
            logger.warning("Failed to auto-configure JaCoCo in %s: %s", gradle_kts_path, e)
            return False

    @staticmethod
    def find_jacoco_report(project_dir: Path) -> Optional[Path]:
        """Find the primary JaCoCo XML report within a project directory."""
        if not project_dir.exists() or not project_dir.is_dir():
            return None

        # Check standard locations first
        for rel_path in STANDARD_JACOCO_XML_PATHS:
            candidate = project_dir / rel_path
            if candidate.exists() and candidate.is_file() and candidate.stat().st_size > 0:
                return candidate

        # Fallback search for any jacoco*.xml file (ignoring git/node_modules/storage)
        for xml_file in project_dir.rglob("jacoco*.xml"):
            path_str = str(xml_file)
            if ".git" in path_str or "node_modules" in path_str or "storage" in path_str:
                continue
            if xml_file.is_file() and xml_file.stat().st_size > 0:
                return xml_file

        return None

    @staticmethod
    def parse_jacoco_xml(xml_path: Path) -> Dict[str, Any]:
        """Parses a JaCoCo XML report and returns coverage statistics."""
        if not xml_path.exists() or not xml_path.is_file():
            return {
                "available": False,
                "error": f"JaCoCo report not found: {xml_path}",
                "message": f"JaCoCo XML report was not generated at {xml_path}",
                "line_coverage_pct": None,
                "branch_coverage_pct": None,
                "instruction_coverage_pct": None,
                "method_coverage_pct": None,
                "class_coverage_pct": None,
                "lines_covered": 0,
                "lines_missed": 0,
                "lines_total": 0,
                "branches_covered": 0,
                "branches_missed": 0,
                "branches_total": 0,
                "instructions_covered": 0,
                "instructions_missed": 0,
                "instructions_total": 0,
                "methods_covered": 0,
                "methods_missed": 0,
                "methods_total": 0,
                "classes_covered": 0,
                "classes_missed": 0,
                "classes_total": 0,
            }

        try:
            tree = ET.parse(xml_path)
            root = tree.getroot()

            counters: Dict[str, Dict[str, Any]] = {}
            for counter in root.findall("counter"):
                c_type = counter.get("type", "")
                missed = int(counter.get("missed", 0))
                covered = int(counter.get("covered", 0))
                total = missed + covered
                pct = round((covered / total) * 100, 2) if total > 0 else 0.0
                counters[c_type] = {
                    "missed": missed,
                    "covered": covered,
                    "total": total,
                    "pct": pct,
                }

            line_data = counters.get("LINE", {"pct": 0.0, "covered": 0, "missed": 0, "total": 0})
            branch_data = counters.get("BRANCH", {"pct": 0.0, "covered": 0, "missed": 0, "total": 0})
            inst_data = counters.get("INSTRUCTION", {"pct": 0.0, "covered": 0, "missed": 0, "total": 0})
            method_data = counters.get("METHOD", {"pct": 0.0, "covered": 0, "missed": 0, "total": 0})
            class_data = counters.get("CLASS", {"pct": 0.0, "covered": 0, "missed": 0, "total": 0})

            packages = [p.get("name", "") for p in root.findall("package") if p.get("name")]

            return {
                "available": True,
                "report_path": str(xml_path),
                "line_coverage_pct": line_data["pct"],
                "branch_coverage_pct": branch_data["pct"],
                "instruction_coverage_pct": inst_data["pct"],
                "method_coverage_pct": method_data["pct"],
                "class_coverage_pct": class_data["pct"],
                "lines_covered": line_data["covered"],
                "lines_missed": line_data["missed"],
                "lines_total": line_data["total"],
                "branches_covered": branch_data["covered"],
                "branches_missed": branch_data["missed"],
                "branches_total": branch_data["total"],
                "instructions_covered": inst_data["covered"],
                "instructions_missed": inst_data["missed"],
                "instructions_total": inst_data["total"],
                "methods_covered": method_data["covered"],
                "methods_missed": method_data["missed"],
                "methods_total": method_data["total"],
                "classes_covered": class_data["covered"],
                "classes_missed": class_data["missed"],
                "classes_total": class_data["total"],
                "packages_count": len(packages),
            }
        except ET.ParseError as err:
            logger.warning("Malformed JaCoCo XML at %s: %s", xml_path, err)
            return {
                "available": False,
                "error": f"Malformed JaCoCo XML: {err}",
                "message": f"Malformed JaCoCo XML: {err}",
                "line_coverage_pct": None,
                "branch_coverage_pct": None,
                "instruction_coverage_pct": None,
                "method_coverage_pct": None,
                "class_coverage_pct": None,
            }
        except Exception as exc:
            logger.warning("Unexpected error parsing JaCoCo XML at %s: %s", xml_path, exc)
            return {
                "available": False,
                "error": str(exc),
                "message": str(exc),
                "line_coverage_pct": None,
                "branch_coverage_pct": None,
                "instruction_coverage_pct": None,
                "method_coverage_pct": None,
                "class_coverage_pct": None,
            }

    @classmethod
    def check_artifacts_exist(cls, project_dir: Path) -> Dict[str, bool]:
        """Check whether essential compilation and JaCoCo coverage artifacts exist."""
        if not project_dir.exists() or not project_dir.is_dir():
            return {
                "target_dir": False,
                "classes_dir": False,
                "test_classes_dir": False,
                "jacoco_exec": False,
                "jacoco_xml": False,
                "all_ready": False,
            }

        target_dir = project_dir / "target"
        classes_dir = target_dir / "classes"
        test_classes_dir = target_dir / "test-classes"
        jacoco_exec = target_dir / "jacoco.exec"
        jacoco_xml = cls.find_jacoco_report(project_dir)

        target_exists = target_dir.exists() and target_dir.is_dir()
        classes_exists = classes_dir.exists() and classes_dir.is_dir()
        test_classes_exists = test_classes_dir.exists() and test_classes_dir.is_dir()
        jacoco_exec_exists = jacoco_exec.exists() and jacoco_exec.is_file() and jacoco_exec.stat().st_size > 0
        jacoco_xml_exists = jacoco_xml is not None and jacoco_xml.exists() and jacoco_xml.stat().st_size > 0

        all_ready = target_exists and classes_exists and test_classes_exists and jacoco_exec_exists and jacoco_xml_exists

        return {
            "target_dir": target_exists,
            "classes_dir": classes_exists,
            "test_classes_dir": test_classes_exists,
            "jacoco_exec": jacoco_exec_exists,
            "jacoco_xml": jacoco_xml_exists,
            "all_ready": all_ready,
        }

    @classmethod
    def detect_target_major(cls, project_dir: Path) -> Optional[int]:
        """Detect the target Java major version from pom.xml / build.gradle."""
        if not project_dir.exists() or not project_dir.is_dir():
            return None

        pom_path = project_dir / "pom.xml"
        if pom_path.exists() and pom_path.is_file():
            try:
                import defusedxml.ElementTree as DetET
                from app.infrastructure.analyzers.java_version_detector import JavaVersionDetector
                tree = DetET.parse(pom_path)
                detector = JavaVersionDetector()
                ver_str = detector.detect("maven", tree.getroot(), "", "")
                if ver_str and ver_str != "UNKNOWN" and ver_str.isdigit():
                    return int(ver_str)
            except Exception:
                pass
            try:
                content = pom_path.read_text(encoding="utf-8", errors="replace")
                for pattern in (
                    r"<java\.version>(\d+)</java\.version>",
                    r"<maven\.compiler\.release>(\d+)</maven\.compiler\.release>",
                    r"<maven\.compiler\.target>1?\.?(\d+)</maven\.compiler\.target>",
                    r"<maven\.compiler\.source>1?\.?(\d+)</maven\.compiler\.source>",
                    r"<target>1?\.?(\d+)</target>",
                    r"<release>(\d+)</release>",
                ):
                    match = re.search(pattern, content)
                    if match:
                        return int(match.group(1))
            except Exception:
                pass

        gradle_path = project_dir / "build.gradle"
        gradle_props = project_dir / "gradle.properties"
        if gradle_path.exists() and gradle_path.is_file():
            try:
                from app.infrastructure.analyzers.java_version_detector import JavaVersionDetector
                b_text = gradle_path.read_text(encoding="utf-8", errors="replace")
                p_text = gradle_props.read_text(encoding="utf-8", errors="replace") if gradle_props.exists() else ""
                detector = JavaVersionDetector()
                ver_str = detector.detect("gradle", None, b_text, p_text)
                if ver_str and ver_str != "UNKNOWN" and ver_str.isdigit():
                    return int(ver_str)
            except Exception:
                pass

        return None

    @classmethod
    def run_jacoco_build(
        cls,
        project_dir: Path,
        target_major: int | None = None,
        test_targets: list[str] | None = None,
        timeout: int = 180,
    ) -> Dict[str, Any]:
        """Automatically builds and executes tests with JaCoCo agent enabled for the project."""
        if not project_dir.exists() or not project_dir.is_dir():
            return {
                "available": False,
                "error": f"Project directory does not exist: {project_dir}",
                "message": f"Project directory does not exist: {project_dir}",
                "line_coverage_pct": None,
                "branch_coverage_pct": None,
                "instruction_coverage_pct": None,
                "method_coverage_pct": None,
                "class_coverage_pct": None,
            }

        pom_path = project_dir / "pom.xml"
        gradle_path = project_dir / "build.gradle"
        gradle_kts_path = project_dir / "build.gradle.kts"

        if not (pom_path.exists() or gradle_path.exists() or gradle_kts_path.exists()):
            return {
                "available": False,
                "error": f"No build file (pom.xml/build.gradle) found in {project_dir}",
                "message": f"No build file (pom.xml/build.gradle) found in {project_dir}",
                "line_coverage_pct": None,
                "branch_coverage_pct": None,
                "instruction_coverage_pct": None,
                "method_coverage_pct": None,
                "class_coverage_pct": None,
            }

        # Auto-configure JaCoCo if missing
        cls.ensure_jacoco_configured(project_dir)

        # Detect target Java version dynamically if not explicitly given
        if target_major is None:
            target_major = cls.detect_target_major(project_dir)

        is_windows = os.name == "nt"
        is_gradle = (gradle_path.exists() or gradle_kts_path.exists()) and not pom_path.exists()

        if is_gradle:
            gradlew_bat = project_dir / "gradlew.bat"
            gradlew_sh = project_dir / "gradlew"
            if is_windows and gradlew_bat.exists():
                executable = str(gradlew_bat.resolve())
            elif not is_windows and gradlew_sh.exists():
                executable = str(gradlew_sh.resolve())
            else:
                executable = resolve_executable("gradle")
                if not executable:
                    executable = "gradle.bat" if is_windows else "gradle"
            cmd = [executable, "clean", "test", "jacocoTestReport"]
            if test_targets:
                for name in test_targets:
                    cmd.extend(["--tests", f"*{name}*"])
        else:
            mvnw_cmd = project_dir / "mvnw.cmd"
            mvnw_sh = project_dir / "mvnw"
            if is_windows and mvnw_cmd.exists():
                executable = str(mvnw_cmd.resolve())
            elif not is_windows and mvnw_sh.exists():
                executable = str(mvnw_sh.resolve())
            else:
                executable = resolve_executable("mvn")
                if not executable:
                    executable = "mvn.cmd" if is_windows else "mvn"
            cmd = [
                executable,
                "clean",
                "org.jacoco:jacoco-maven-plugin:0.8.13:prepare-agent",
                "test",
                "org.jacoco:jacoco-maven-plugin:0.8.13:report",
                "-DfailIfNoTests=false",
                "-DtestFailureIgnore=true",
                "-Dmaven.test.failure.ignore=true",
                "-Dgit.commit.id.skip=true",
                "-Dmaven.gitcommitid.skip=true",
                "surefire-report:report",
            ]
            if test_targets:
                cmd.append(f"-Dtest={','.join([f'*{n}*' for n in test_targets])}")

        logger.info("[JACOCO] Executing Maven test suite with JaCoCo on %s (detected Java: %s, timeout: %ds)", project_dir, target_major, timeout)
        from app.infrastructure.java_runtime import build_tool_env
        env = build_tool_env(target_major)
        dir_lock = cls._get_dir_lock(project_dir)
        try:
            with dir_lock:
                res = run_command(cmd, cwd=project_dir, timeout=timeout, env=env)
        except Exception as exec_err:
            logger.warning("[JACOCO] JaCoCo build execution failed on %s: %s", project_dir, exec_err)
            return {
                "available": False,
                "line_coverage_pct": None,
                "branch_coverage_pct": None,
                "instruction_coverage_pct": None,
                "method_coverage_pct": None,
                "class_coverage_pct": None,
                "report_path": None,
                "message": f"JaCoCo build execution failed or timed out: {exec_err}",
                "error": str(exec_err),
                "exit_code": -1,
            }

        # Check if JaCoCo report was generated
        report_file = cls.find_jacoco_report(project_dir)
        if report_file and report_file.exists() and report_file.stat().st_size > 0:
            parsed = cls.parse_jacoco_xml(report_file)
            try:
                rel = str(report_file.relative_to(project_dir)).replace("\\", "/")
                parsed["report_path"] = rel
            except Exception:
                pass
            parsed["exit_code"] = res.exit_code
            return parsed

        # If compilation/execution failed and no XML report was generated, return unavailable with actual failure reason
        err_output = res.stderr or res.stdout or "Maven build failed without generating JaCoCo report"
        failure_lines = []
        for line in err_output.splitlines():
            if "[ERROR]" in line or "BUILD FAILURE" in line or "Compilation failure" in line:
                failure_lines.append(line.strip())
        failure_reason = "\n".join(failure_lines) if failure_lines else err_output[:500]

        logger.warning("[JACOCO] JaCoCo report generation failed on %s. Exit code: %d. Error: %s", project_dir, res.exit_code, failure_reason)
        return {
            "available": False,
            "line_coverage_pct": None,
            "branch_coverage_pct": None,
            "instruction_coverage_pct": None,
            "method_coverage_pct": None,
            "class_coverage_pct": None,
            "report_path": None,
            "message": f"JaCoCo report generation failed: {failure_reason.strip()}",
            "error": failure_reason.strip(),
            "exit_code": res.exit_code,
            "raw_output": err_output,
        }

    @classmethod
    def get_coverage_summary(
        cls,
        project_dir: Path,
        auto_execute_if_missing: bool = False,
        target_major: int | None = None,
        timeout: int = 180,
    ) -> Dict[str, Any]:
        """Discovers and parses the JaCoCo report in project_dir.
        
        If target artifacts or JaCoCo report are missing and auto_execute_if_missing is True,
        automatically runs the build with JaCoCo enabled using the project's detected Java version.
        """
        if not project_dir.exists() or not project_dir.is_dir():
            return {
                "available": False,
                "line_coverage_pct": None,
                "branch_coverage_pct": None,
                "instruction_coverage_pct": None,
                "method_coverage_pct": None,
                "class_coverage_pct": None,
                "report_path": None,
                "message": f"Directory not found: {project_dir}",
            }

        report_file = cls.find_jacoco_report(project_dir)
        if report_file and report_file.exists() and report_file.stat().st_size > 0:
            parsed = cls.parse_jacoco_xml(report_file)
            try:
                rel = str(report_file.relative_to(project_dir)).replace("\\", "/")
                parsed["report_path"] = rel
            except Exception:
                pass
            return parsed

        if auto_execute_if_missing:
            return cls.run_jacoco_build(project_dir, target_major=target_major, timeout=timeout)

        return {
            "available": False,
            "line_coverage_pct": None,
            "branch_coverage_pct": None,
            "instruction_coverage_pct": None,
            "method_coverage_pct": None,
            "class_coverage_pct": None,
            "report_path": None,
            "message": "JaCoCo XML report was not generated.",
        }

    @staticmethod
    def calculate_improvement(
        original: Dict[str, Any], final: Dict[str, Any]
    ) -> Dict[str, Any]:
        """Calculates coverage delta in percentage points between baseline and final runs."""
        orig_avail = bool(original.get("available") and original.get("line_coverage_pct") is not None)
        final_avail = bool(final.get("available") and final.get("line_coverage_pct") is not None)

        if not final_avail:
            return {
                "line_coverage_pp": None,
                "branch_coverage_pp": None,
                "instruction_coverage_pp": None,
                "text": None,
                "branch_text": None,
                "instruction_text": None,
            }

        final_line = float(final["line_coverage_pct"])
        final_branch = float(final.get("branch_coverage_pct") or 0.0)
        final_inst = float(final.get("instruction_coverage_pct") or 0.0)

        if not orig_avail:
            return {
                "line_coverage_pp": None,
                "branch_coverage_pp": None,
                "instruction_coverage_pp": None,
                "text": f"{final_line:.1f}%",
                "branch_text": f"{final_branch:.1f}%",
                "instruction_text": f"{final_inst:.1f}%",
            }

        orig_line = float(original["line_coverage_pct"])
        line_delta = round(final_line - orig_line, 2)

        orig_branch = float(original.get("branch_coverage_pct") or 0.0)
        branch_delta = round(final_branch - orig_branch, 2)

        orig_inst = float(original.get("instruction_coverage_pct") or 0.0)
        inst_delta = round(final_inst - orig_inst, 2)

        return {
            "line_coverage_pp": line_delta,
            "branch_coverage_pp": branch_delta,
            "instruction_coverage_pp": inst_delta,
            "text": f"+{line_delta} pp" if line_delta >= 0 else f"{line_delta} pp",
            "branch_text": f"+{branch_delta} pp" if branch_delta >= 0 else f"{branch_delta} pp",
            "instruction_text": f"+{inst_delta} pp" if inst_delta >= 0 else f"{inst_delta} pp",
        }
