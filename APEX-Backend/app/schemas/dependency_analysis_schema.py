"""Request/response schemas for LLM-powered Dependency Risk & Migration Analysis."""

from __future__ import annotations

from typing import Any, Optional
from pydantic import BaseModel, Field


class DependencyItemInput(BaseModel):
    """Input representation of a dependency discovered in the repository."""

    group_id: Optional[str] = None
    artifact_id: Optional[str] = None
    current_version: Optional[str] = None
    resolved_version: Optional[str] = None
    scope: Optional[str] = None
    status: Optional[str] = None
    category: Optional[str] = None
    type: Optional[str] = None
    direct: Optional[bool] = None
    transitive: Optional[bool] = None
    parent: Optional[str] = None
    introduced_by: Optional[str] = None


class DependencyAnalysisRequest(BaseModel):
    """Body for ``POST /api/dependency-analysis``."""

    dependencies: list[DependencyItemInput] = Field(default_factory=list)
    source_java_version: Optional[str] = None
    target_java_version: Optional[str] = None
    build_tool: Optional[str] = None
    frameworks: list[Any] = Field(default_factory=list)
    testing_frameworks: list[Any] = Field(default_factory=list)
    spring_boot_version: Optional[str] = None
    api_endpoint_count: int = 0
    job_id: Optional[str] = None


class AnalyzedDependencyItem(BaseModel):
    """Individual dependency assessment generated by the LLM."""

    id: str
    group: str = ""
    artifact: str = ""
    name: str = ""
    version: str = "unknown"
    recommended_version: str = "Not Determined"
    upgrade_status: str = "REVIEW REQUIRED"
    source: str = ""
    java_compatibility: str = "Unknown"
    framework_compatibility: str = "Unknown"
    upgrade_reason: str = ""
    upgrade_confidence: str = "Low"
    category: str = "Utility"
    risk: str = "LOW"  # CRITICAL, HIGH, MEDIUM, LOW
    explanation: str = ""
    recommendation: str = ""
    scope: Optional[str] = "compile"
    direct: bool = True
    transitive: bool = False
    parent: Optional[str] = None
    introduced_by: Optional[str] = None


class DependencyRiskCounts(BaseModel):
    """Calculated counts of dependencies in each risk level."""

    critical: int = 0
    high: int = 0
    medium: int = 0
    low: int = 0
    total: int = 0


class DependencyAnalysisResponse(BaseModel):
    """Success body for ``POST /api/dependency-analysis``."""

    overall_risk: str = "LOW"  # CRITICAL, HIGH, MEDIUM, LOW
    complexity: str = "LIGHT"  # NONE, LIGHT, MODERATE, COMPLEX
    overall_explanation: str = ""
    complexity_explanation: str = ""
    counts: DependencyRiskCounts = Field(default_factory=DependencyRiskCounts)
    dependencies: list[AnalyzedDependencyItem] = Field(default_factory=list)
    provider_used: str = "huggingface"
    current_spring_boot_version: Optional[str] = None
    target_spring_boot_version: Optional[str] = None
